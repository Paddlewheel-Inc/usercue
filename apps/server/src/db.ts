import { SQL } from "bun";
import { env } from "./env";

const tx = new AsyncLocalStorage<SQL>();
// Without `bigint`, Bun returns BIGINT and COUNT(*) as strings. mapRow turns BigInt into numbers.
const SQL_OPTIONS = { bigint: true };
let pool = new SQL(env.databaseUrl, SQL_OPTIONS);

function client(): SQL {
  return tx.getStore() ?? pool;
}

function isParams(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function bind(text: string, args: unknown[]): { text: string; values: unknown[] } {
  if (args.length === 1 && isParams(args[0]) && !text.includes("?")) {
    const obj = args[0];
    const values: unknown[] = [];
    const index = new Map<string, number>();
    const converted = text.replace(/\$([a-zA-Z_][a-zA-Z0-9_]*)/g, (_, name: string) => {
      let n = index.get(name);
      if (n === undefined) {
        n = values.length + 1;
        index.set(name, n);
        values.push(obj[name] ?? null);
      }
      return `$${n}`;
    });
    return { text: converted, values };
  }

  let n = 0;
  return { text: text.replaceAll("?", () => `$${++n}`), values: args };
}

function mapRow<T>(value: Record<string, unknown> | undefined): T | undefined {
  if (!value) return undefined;
  const out: Record<string, unknown> = {};
  for (const [key, item] of Object.entries(value)) {
    out[key] = typeof item === "bigint" ? Number(item) : item;
  }
  return out as T;
}

class Statement<T> {
  constructor(private text: string) {}

  async get(...args: unknown[]): Promise<T | undefined> {
    const { text, values } = bind(this.text, args);
    const rows = await client().unsafe(text, values);
    return mapRow<T>(rows[0] as Record<string, unknown> | undefined);
  }

  async all(...args: unknown[]): Promise<T[]> {
    const { text, values } = bind(this.text, args);
    const rows = await client().unsafe(text, values);
    return (rows as Record<string, unknown>[]).map((row) => mapRow<T>(row)!);
  }

  async run(...args: unknown[]): Promise<{ changes: number }> {
    const { text, values } = bind(this.text, args);
    const result = await client().unsafe(text, values);
    return { changes: Number((result as { count?: number }).count ?? result.length) };
  }
}

export const db = {
  query<T, _P = unknown>(text: string) {
    return new Statement<T>(text);
  },
  async exec(text: string) {
    await client().unsafe(text).simple();
  },
  transaction<T>(fn: () => Promise<T>): Promise<T> {
    return pool.begin((sql) => tx.run(sql, fn));
  },
};

