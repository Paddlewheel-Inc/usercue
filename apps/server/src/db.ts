function ident(name: string): string {
  if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(name)) {
    throw new Error(`Invalid postgres identifier: ${name}`);
  }
  return name;
}

function literal(value: string): string {
  return `'${value.replaceAll("'", "''")}'`;
}

function isLocalHost(hostname: string): boolean {
  return (
    hostname === "localhost" ||
    hostname === "127.0.0.1" ||
    hostname === "[::1]" ||
    hostname === "::1"
  );
}

function pgCode(err: unknown): string | undefined {
  return err && typeof err === "object" && "code" in err
    ? String((err as { code?: unknown }).code)
    : undefined;
}

function pgMessage(err: unknown): string {
  return err instanceof Error ? err.message : String(err);
}

async function ensureLocalDatabase() {
  const url = new URL(env.databaseUrl);
  if (!isLocalHost(url.hostname)) return;

  const role = decodeURIComponent(url.username) || process.env.USER || "postgres";
  const password = decodeURIComponent(url.password);
  const database = url.pathname.replace(/^\//, "") || "usercue";
  const adminUser = process.env.USER || "postgres";

  const adminUrl = new URL(env.databaseUrl);
  adminUrl.username = adminUser;
  adminUrl.password = "";
  adminUrl.pathname = "/postgres";

  const admin = new SQL(adminUrl.toString());
  try {
    await admin`SELECT 1`;
    const existingRole = await admin`SELECT 1 FROM pg_roles WHERE rolname = ${role}`;
    if (!existingRole.length) {
      const passwordSql = password ? ` PASSWORD ${literal(password)}` : "";
      await admin.unsafe(`CREATE ROLE ${ident(role)} WITH LOGIN${passwordSql}`);
    } else if (password) {
      await admin.unsafe(`ALTER ROLE ${ident(role)} WITH LOGIN PASSWORD ${literal(password)}`);
    }

    const existingDb = await admin`SELECT 1 FROM pg_database WHERE datname = ${database}`;
    if (!existingDb.length) {
      await admin.unsafe(`CREATE DATABASE ${ident(database)} OWNER ${ident(role)}`);
    }
  } finally {
    await admin.end();
  }
}

export async function initDb() {
  let last: unknown;
  let provisioned = false;
  for (let i = 0; i < 30; i++) {
    try {
      await pool`SELECT 1`;
      await db.exec(SCHEMA);
      await db.exec(MIGRATE);
      return;
    } catch (err) {
      last = err;
      const message = pgMessage(err);
      const missing =
        /role .* does not exist/i.test(message) || /database .* does not exist/i.test(message);
      if (missing && !provisioned) {
        provisioned = true;
        try {
          await ensureLocalDatabase();
          await pool.end();
          pool = new SQL(env.databaseUrl, SQL_OPTIONS);
          continue;
        } catch (provisionErr) {
          last = provisionErr;
        }
      }
      if (
        pgCode(err) === "ERR_POSTGRES_CONNECTION_TIMEOUT" ||
        /ECONNREFUSED|connection/i.test(message)
      ) {
        await Bun.sleep(500);
        continue;
      }
      if (missing) break;
      await Bun.sleep(500);
    }
  }
  throw last instanceof Error ? last : new Error("Could not connect to postgres");
}

